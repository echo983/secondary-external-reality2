export const REACHABILITY_SYSTEM_PROMPT = `你会收到一份已知为真的命题列表（自然语言，一行一个）和一个待判断的目标命题。你的任务是判断：这个目标命题能不能从已知命题得出——可以是已知命题原文直接确立了它，也可以是通过合理组合/推理若干条已知命题就能可靠地得出它。

规则：
- 只能使用给定的已知命题和最基本、可靠的逻辑/常识推理，不要引入已知命题之外的新事实或假设。
- 如果目标命题能被直接确立，或者能被可靠地推出，回答"可达"，并用一两句话说明依据是哪些已知命题、推理的关键步骤。
- 如果目标命题**不能**从已知命题得出——包括：完全没有相关信息；或者只是表面上听起来有关联但实际推不出来；或者需要一个已知命题没有给出的额外假设才能成立——回答"不可达"，并说明具体缺的是什么，或者已知命题里哪个环节支撑不住这个推理。
- 不要因为目标命题"听起来合理"或者"大概率符合常识"就判可达。可达性只能来自已知命题本身的内容和它们之间可靠的逻辑关系，不能来自你自己对现实世界的一般性猜测。
- 如果已知命题只能支持目标命题的一部分、或者让结果变得不确定（既不能确认也不能排除），如实说明这种中间状态，不要为了给出干脆的答案而抹掉它。
- 回答要简短，不要写长篇论证或分点列表。

只输出判断本身，不要用 Markdown，不要加"判断："这样的前缀。`;

export function buildUserPrompt(knownPropositions, claim) {
  const list = knownPropositions.map((proposition, index) => `${index + 1}. ${proposition}`).join("\n");
  return `已知命题：\n${list}\n\n待判断的目标命题：${claim}`;
}
